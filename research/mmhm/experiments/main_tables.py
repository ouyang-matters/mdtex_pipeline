#!/usr/bin/env python3
r"""Main-text tables of the paper, from the pooled summaries written by
aggregate.py (results/summary.csv, results/summary_pairs.csv). No new runs.

  tab_main_summary.tex  cross-workload summary at one representative instance
                        per family: amortised and p99 latency of the static
                        reference, of the insertion-order DRB (drb-id) and of
                        mmhm, and the amortised speedups over the reference.
  tab_ablation.tex      the four DRB variants side by side (amortised latency),
                        best per row in bold, ties within noise marked.
  numbers_main.tex      \NumMain... macros: ranges of the speedups of the DRB
                        variants over the faster static reference, and of their
                        p99 relative to it, per workload family.

"Within noise" is the paper's criterion: the per-seed ranges of the two
methods overlap (summary_pairs.csv, column amort_overlap / p99_overlap).
Run after aggregate.py:  python3 main_tables.py
"""
import os

import pandas as pd

from aggregate import GEN, RES, intc, pretty_inst, sig

S = pd.read_csv(os.path.join(RES, "summary.csv"))
P = pd.read_csv(os.path.join(RES, "summary_pairs.csv"))

# exp, workload. The static reference of a row is the faster (amortised) of
# full-id and full-sorted; full-sorted did not run on the W5 witnesses.
SUMMARY_ROWS = [("E1", "w2_N33_s8"), ("E3", "w3_N27_k2"), ("E4", "w4_2d_n16000_D2"),
                ("E5", "w1_sphere_L7"), ("E5", "w1_torus_500"),
                ("E6", "w5a_L1000000"), ("E6", "w5b_L8")]
ABLATION_ROWS = [("E1", "w2_N33_s8"), ("E3", "w3_N20_k2"), ("E3", "w3_N27_k2"),
                 ("E4", "w4_2d_n16000_D2"), ("E5", "w1_sphere_L7"), ("E5", "w1_torus_500"),
                 ("E6", "w5a_L1000000"), ("E6", "w5b_L8")]
DRB = ["drb-id", "mmhm-norb", "drb-id-rb", "mmhm"]
NOISE = r"$^{\circ}$"


def _write(name, lines):
    with open(os.path.join(GEN, name), "w", encoding="utf-8") as fh:
        fh.write("% Generated by experiments/main_tables.py -- do not edit.\n")
        fh.write("\n".join(lines) + "\n")


def static_ref(exp, w):
    have = S[(S.exp == exp) & (S.workload == w) & S.method.isin(["full-id", "full-sorted"])]
    return have.sort_values("amort_us").iloc[0].method


def row(exp, w, m):
    r = S[(S.exp == exp) & (S.workload == w) & (S.method == m)]
    assert len(r) == 1, (exp, w, m, len(r))
    return r.iloc[0]


def overlap(exp, w, a, b, col="amort_overlap"):
    if a == b:
        return True
    r = P[(P.exp == exp) & (P.workload == w) & (((P.a == a) & (P.b == b)) | ((P.a == b) & (P.b == a)))]
    assert len(r) == 1, (exp, w, a, b, len(r))
    return bool(r.iloc[0][col])


def ms(x):
    return sig(float(x) / 1000.0, 3)


def summary():
    lines = [r"\begin{tabular}{@{}l r rr rr rr rr@{}}", r"\toprule",
             r" & & \multicolumn{2}{c}{static reference} & \multicolumn{2}{c}{\method{drb-id}}"
             r" & \multicolumn{2}{c}{\method{mmhm}} & \multicolumn{2}{c}{speedup} \\",
             r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(lr){7-8}\cmidrule(l){9-10}",
             r"instance & $|K_0|$ & amort. & p99 & amort. & p99 & amort. & p99"
             r" & \method{drb-id} & \method{mmhm} \\", r"\midrule"]
    for exp, w in SUMMARY_ROWS:
        ref = static_ref(exp, w)
        r0, r1, r2 = row(exp, w, ref), row(exp, w, "drb-id"), row(exp, w, "mmhm")
        mark = r"$^{\mathrm{s}}$" if ref == "full-sorted" else r"$^{\mathrm{i}}$"
        cells = [pretty_inst(w), intc(r0.K0)]
        for r, m in ((r0, ref), (r1, "drb-id"), (r2, "mmhm")):
            p99 = ms(r.lat_p99_us)
            if m != ref and r.lat_p99_us > r0.lat_p99_us and not overlap(exp, w, ref, m,
                                                                            "p99_overlap"):
                p99 = r"\textbf{" + p99 + "}"
            cells += [ms(r.amort_us) + (mark if m == ref else ""), p99]
        for r, m in ((r1, "drb-id"), (r2, "mmhm")):
            s = float(r0.amort_us) / float(r.amort_us)
            cells.append(sig(s, 3) + (NOISE if overlap(exp, w, ref, m) else ""))
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    _write("tab_main_summary.tex", lines)


def ablation():
    lines = [r"\begin{tabular}{@{}l rrrr r@{}}", r"\toprule",
             r"instance & \method{drb-id} & \method{mmhm-norb} & \method{drb-id-rb} & "
             r"\method{mmhm} & rebuilds \\", r"\midrule"]
    for exp, w in ABLATION_ROWS:
        rs = {m: row(exp, w, m) for m in DRB}
        best = min(DRB, key=lambda m: float(rs[m].amort_us))
        cells = [pretty_inst(w)]
        for m in DRB:
            v = ms(rs[m].amort_us)
            if m == best:
                v = r"\textbf{" + v + "}"
            elif overlap(exp, w, best, m):
                v += NOISE
            cells.append(v)
        rb = f"{sig(rs['drb-id-rb'].rebuilds, 2)} / {sig(rs['mmhm'].rebuilds, 2)}"
        cells.append(rb)
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    _write("tab_ablation.tex", lines)


def speedups(exp, sel, methods=DRB):
    """(speedup, p99 ratio) over the faster static reference, for every instance of
    experiment exp whose workload satisfies sel and every method in methods."""
    out = []
    for w in sorted(S[(S.exp == exp)].workload.unique()):
        if not sel(w):
            continue
        ref = row(exp, w, static_ref(exp, w))
        for m in methods:
            r = row(exp, w, m)
            out.append((float(ref.amort_us) / float(r.amort_us),
                        float(r.lat_p99_us) / float(ref.lat_p99_us)))
    return out


def macros():
    M = []

    def rng(name, vals, n=3):
        M.append((f"NumMain{name}Min", sig(min(vals), n)))
        M.append((f"NumMain{name}Max", sig(max(vals), n)))

    big = speedups("E1", lambda w: w == "w2_N33_s8")
    rng("WTwoLargestSpeedup", [a for a, _ in big])
    rng("WTwoSmallestSpeedup", [a for a, _ in speedups("E1", lambda w: w == "w2_N7_s8")])
    mm3 = speedups("E3", lambda w: True, ["mmhm"])
    rng("WThreeMmhmSpeedup", [a for a, _ in mm3])
    rng("WFourSpeedup", [a for a, _ in speedups("E4", lambda w: True)])
    rng("WFourLargeSpeedup", [a for a, _ in speedups("E4", lambda w: "_n1000_" not in w)])
    rng("WFourSmallSpeedup", [a for a, _ in speedups("E4", lambda w: "_n1000_" in w)])
    w1 = speedups("E5", lambda w: True)
    rng("WOneSpeedup", [a for a, _ in w1])
    rng("WOneProbNinetyNineRatio", [b for _, b in w1])
    lines = ["% Generated by experiments/main_tables.py -- do not edit.",
             "% Speedup: ratio of amortised latencies over the same updates, against the",
             "% faster (amortised) of full-id and full-sorted on that instance; ProbNinetyNineRatio:",
             "% p99 of the DRB variant divided by the p99 of that reference.",
             "% Variants: drb-id, mmhm-norb, drb-id-rb, mmhm (WThreeMmhm...: mmhm only)."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in M]
    with open(os.path.join(GEN, "numbers_main.tex"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    summary()
    ablation()
    macros()
    print("wrote", os.path.join(GEN, "tab_main_summary.tex"), "and tab_ablation.tex")
